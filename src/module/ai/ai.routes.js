import express from "express";
const router = express.Router();
import * as AiController from "./ai.controller.js";
import { authenticate } from "../auth/auth.middleware.js";
router.post("/create",authenticate, AiController.aiResponseCreate);
router.get("/get/title",authenticate, AiController.aiSessionTitleFind);
router.get("/get/:id",authenticate, AiController.aiResponseFind);
router.delete("/delete/:id",authenticate, AiController.aiResponseDelete);
router.put("/update/:id",authenticate, AiController.aiResponseSessionTitleUpdate);
export default router;
